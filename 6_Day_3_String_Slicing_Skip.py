## #6.1 string Indexing and Slicing

Name="DataAnalytics"
print("First Word strait is :",Name[:4])
print("Second Word Strait is :",Name[4:13])               
print("Skipping 2nd Word Strait is :",Name[0:13:2])  
print("Skipping 2nd Word Strait is :",Name[0:13:3])                 
print("Second Word Reverse is :",Name[-9:])               
print("Skiping 3rd Word is Reverse is :",Name[-13:-9:3])
